    private static String offset(long ms) {
        return "+" + (ms / 1000) + "." + String.format(Locale.ROOT, "%03d", Math.abs(ms % 1000)) + "s";
    }

    private static String tick(double v, double step) {
        if (step >= 1.0) {
            return Long.toString(Math.round(v));
        }
        return step >= 0.1 ? String.format(Locale.ROOT, "%.1f", v) : String.format(Locale.ROOT, "%.2f", v);
    }

    private static String hex(int rgb) {
        return String.format(Locale.ROOT, "#%06x", rgb & 0xFFFFFF);
    }

    private static String r(double v) {
        return String.format(Locale.ROOT, "%.1f", v);
    }

    static String fmt(double v) {
        return String.format(Locale.ROOT, "%.2f", v);
    }

    static String esc(String in) {
        if (in == null) {
            return "";
        }
        return in.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }
